import type { Metadata } from "next";

import { getContent, siteUrl, type Locale } from "@/data";

/** Page metadata for the home page of a locale (also the base for project pages). */
export function buildMetadata(locale: Locale): Metadata {
  const { meta, base } = getContent(locale);
  const path = base || "/";

  return {
    metadataBase: new URL(siteUrl),
    title: meta.title,
    description: meta.description,
    keywords: [
      "Abdurrahman Al-Azhari",
      "عبدالرحمن الأزهري",
      "Frontend Engineer",
      "React.js Developer",
      "Next.js Developer",
      "TypeScript",
      "Cairo",
      "Egypt",
    ],
    authors: [{ name: "Abdurrahman Al-Azhari", url: siteUrl }],
    alternates: {
      canonical: path,
      languages: { en: "/", ar: "/ar", "x-default": "/" },
    },
    // Google Search Console ownership check (HTML tag method)
    verification: { google: "GDye4cSWlvJargdgTCNQjOSB55t3eDhY3cWvSjDAkqo" },
    openGraph: {
      title: meta.title,
      description: meta.description,
      url: path,
      siteName: meta.siteName,
      type: "website",
      locale: locale === "ar" ? "ar_EG" : "en_US",
      // Generated by app/og/route.tsx; shared by both languages.
      images: [{ url: "/og", width: 1200, height: 630, alt: meta.title }],
    },
    twitter: {
      card: "summary_large_image",
      title: meta.title,
      description: meta.description,
      images: [{ url: "/og", width: 1200, height: 630, alt: meta.title }],
    },
    icons: {
      icon: [
        { url: "/favicon.ico", sizes: "any" },
        { url: "/favicon-32x32.png", sizes: "32x32", type: "image/png" },
        { url: "/favicon-16x16.png", sizes: "16x16", type: "image/png" },
      ],
      apple: "/apple-touch-icon.png",
    },
    manifest: "/site.webmanifest",
  };
}
